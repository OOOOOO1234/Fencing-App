import { computeStats, formatPct, formatTime, scoreStateOf } from './stats'
import { OUTCOME_LABELS, type Bout } from '../types'

export function boutToCsv(bout: Bout): string {
  const header = [
    'timestamp',
    'time',
    'action',
    'outcome',
    'score_you',
    'score_them',
    'score_state',
    'initiative',
    'remark',
  ]
  const rows = bout.phrases.map((p) =>
    [
      String(p.timestamp),
      formatTime(p.timestamp),
      p.action,
      OUTCOME_LABELS[p.outcome],
      p.scoreYou ?? '',
      p.scoreThem ?? '',
      scoreStateOf(p),
      p.initiative ?? '',
      (p.remark ?? '').replaceAll('"', '""'),
    ]
      .map((cell) => `"${cell}"`)
      .join(','),
  )
  return [header.join(','), ...rows].join('\n')
}

export function boutSummaryText(bout: Bout): string {
  const stats = computeStats(bout.phrases)
  const lines = [
    `${bout.title} — analyzing ${bout.side} fencer`,
    `Attempts ${stats.totals.attempts} · Success ${formatPct(stats.totals.successRate)} · Cost ${formatPct(stats.totals.costRate)} · Net ${stats.totals.net}`,
    '',
    'By action:',
  ]
  for (const row of stats.byAction.filter((r) => r.attempts > 0)) {
    lines.push(
      `- ${row.action}: ${row.attempts} try, ${formatPct(row.successRate)} success, ${formatPct(row.costRate)} cost, net ${row.net}`,
    )
  }
  lines.push('', 'Generated by TouchStat (manual tags unless AI key was used).')
  return lines.join('\n')
}

export function downloadText(filename: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}
